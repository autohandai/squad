//! The macOS app owns UserNotifications permission, delivery and click routing.
//! A bridge queue replaces AppleScript when the app starts it. The queue is
//! polled even with hidden windows; OS submission is acknowledged persistently.
use crate::{lock, Shell, MAIN_WINDOW};
use serde::Serialize;
use std::sync::Arc;
use tauri::{AppHandle, Url, WebviewWindow};

#[derive(Serialize)]
pub(crate) struct PermissionReply {
    permission: String,
}

fn trusted_caller(window: &WebviewWindow, shell: &Shell) -> Result<(), String> {
    if !matches!(
        window.label(),
        MAIN_WINDOW | crate::quick_chat::QUICK_CHAT_WINDOW
    ) {
        return Err("Notification controls are only available in Squad.".into());
    }
    let origin = lock(&shell.app_url)
        .as_deref()
        .and_then(|value| Url::parse(value).ok())
        .ok_or("Squad is still starting.")?
        .origin();
    let url = window.url().map_err(|error| error.to_string())?;
    if url.origin() != origin || !url.username().is_empty() || url.password().is_some() {
        return Err("Notification request is not from the local Squad app.".into());
    }
    Ok(())
}

#[tauri::command]
pub(crate) async fn squad_notification_permission(
    window: WebviewWindow,
    shell: tauri::State<'_, Arc<Shell>>,
    request: bool,
) -> Result<PermissionReply, String> {
    trusted_caller(&window, &shell)?;
    tauri::async_runtime::spawn_blocking(move || {
        permission(request).map(|permission| PermissionReply { permission })
    })
    .await
    .map_err(|error| error.to_string())?
}

#[tauri::command]
pub(crate) async fn squad_notification_test(
    window: WebviewWindow,
    shell: tauri::State<'_, Arc<Shell>>,
) -> Result<serde_json::Value, String> {
    trusted_caller(&window, &shell)?;
    tauri::async_runtime::spawn_blocking(move || {
        #[cfg(target_os = "macos")]
        {
            if permission(false)? != "granted" { return Err("Allow notifications for Autohand Squad in macOS System Settings first.".into()); }
            macos::submit("squad-test", "Autohand Squad", "Your test notification is ready. Click to open Needs you.", "/work")?;
            Ok(serde_json::json!({"posted":true,"method":"macos-user-notifications","message":"macOS accepted the test notification. Banner display follows your notification settings and Focus mode."}))
        }
        #[cfg(not(target_os = "macos"))]
        { Err("Use the platform notification test in Squad Settings.".into()) }
    }).await.map_err(|error| error.to_string())?
}

#[tauri::command]
pub(crate) fn squad_notification_settings(
    window: WebviewWindow,
    shell: tauri::State<'_, Arc<Shell>>,
) -> Result<(), String> {
    trusted_caller(&window, &shell)?;
    #[cfg(target_os = "macos")]
    return tauri_plugin_opener::open_url(
        "x-apple.systempreferences:com.apple.Notifications-Settings.extension",
        None::<&str>,
    )
    .map_err(|error| error.to_string());
    #[cfg(not(target_os = "macos"))]
    Err("Native notification permissions are managed by your operating system.".into())
}

fn permission(request: bool) -> Result<String, String> {
    #[cfg(target_os = "macos")]
    return macos::permission(request);
    #[cfg(not(target_os = "macos"))]
    {
        let _ = request;
        Ok("unsupported".into())
    }
}

/// Only app routes generated by the bridge notification policy may be opened.
fn notification_route(route: &str) -> Option<String> {
    let url = Url::parse(&format!("http://squad.invalid{route}")).ok()?;
    if !route.starts_with('/')
        || route.starts_with("//")
        || url.host_str() != Some("squad.invalid")
        || url.fragment().is_some()
        || route.len() > 512
    {
        return None;
    }
    let path = url.path();
    if path == "/conversations/new" {
        let pairs: Vec<_> = url.query_pairs().collect();
        return (pairs.len() == 1
            && pairs[0].0 == "member"
            && crate::quick_chat::valid_member_id(&pairs[0].1))
        .then(|| route.into());
    }
    if matches!(
        path,
        "/work" | "/inbox" | "/mission-control" | "/squad" | "/settings"
    ) || path
        .strip_prefix("/channels/")
        .is_some_and(crate::quick_chat::valid_member_id)
    {
        return Some(route.into());
    }
    // Existing conversations carry opaque IDs; no arbitrary executable URL.
    path.strip_prefix("/conversations/")
        .filter(|id| crate::quick_chat::valid_member_id(id))
        .map(|_| route.into())
}

#[cfg(target_os = "macos")]
pub(crate) fn install(app: &AppHandle, shell: Arc<Shell>) {
    macos::install(app, shell);
}

#[cfg(target_os = "macos")]
mod macos {
    use super::*;
    use block2::{DynBlock, RcBlock};
    use objc2::rc::Retained;
    use objc2::runtime::{Bool, ProtocolObject};
    use objc2::{define_class, msg_send, AnyThread, DefinedClass};
    use objc2_foundation::{NSError, NSObject, NSObjectProtocol, NSString};
    use objc2_user_notifications::*;
    use std::collections::{HashMap, HashSet};
    use std::io::Read;
    use std::ptr::NonNull;
    use std::sync::{mpsc, Mutex, OnceLock};
    use std::time::Duration;

    static CLICK_ROUTES: OnceLock<Mutex<HashMap<String, String>>> = OnceLock::new();
    struct DelegateIvars {
        app: AppHandle,
        shell: Arc<Shell>,
    }
    define_class!(
        // SAFETY: NSObject has no subclass requirements; immutable handles and
        // synchronized ivars are safe when the OS calls on a background queue.
        #[unsafe(super = NSObject)]
        #[ivars = DelegateIvars]
        struct SquadNotificationDelegate;
        unsafe impl NSObjectProtocol for SquadNotificationDelegate {}
        unsafe impl UNUserNotificationCenterDelegate for SquadNotificationDelegate {
            #[unsafe(method(userNotificationCenter:willPresentNotification:withCompletionHandler:))]
            fn will_present(
                &self,
                _center: &UNUserNotificationCenter,
                _notification: &UNNotification,
                completion: &DynBlock<dyn Fn(UNNotificationPresentationOptions)>,
            ) {
                completion.call((UNNotificationPresentationOptions::Banner
                    | UNNotificationPresentationOptions::List
                    | UNNotificationPresentationOptions::Sound,));
            }
            #[unsafe(method(userNotificationCenter:didReceiveNotificationResponse:withCompletionHandler:))]
            fn did_receive(
                &self,
                _center: &UNUserNotificationCenter,
                response: &UNNotificationResponse,
                completion: &DynBlock<dyn Fn()>,
            ) {
                let identifier = response.notification().request().identifier().to_string();
                let route = CLICK_ROUTES
                    .get()
                    .and_then(|routes| lock(routes).get(&identifier).cloned());
                if let Some(route) = route.and_then(|route| notification_route(&route)) {
                    let app = self.ivars().app.clone();
                    let handle = app.clone();
                    let shell = self.ivars().shell.clone();
                    let _ = app.run_on_main_thread(move || {
                        // Open the original conversation, including channel
                        // threads, in the main app rather than a browser tab.
                        crate::navigate_app(&handle, &shell, &route);
                    });
                } else {
                    crate::focus_main_window(&self.ivars().app);
                }
                completion.call(());
            }
        }
    );

    pub(super) fn install(app: &AppHandle, shell: Arc<Shell>) {
        let allocated = SquadNotificationDelegate::alloc().set_ivars(DelegateIvars {
            app: app.clone(),
            shell: shell.clone(),
        });
        // SAFETY: NSObject init has its standard inherited signature.
        let delegate: Retained<SquadNotificationDelegate> =
            unsafe { msg_send![super(allocated), init] };
        UNUserNotificationCenter::currentNotificationCenter()
            .setDelegate(Some(ProtocolObject::from_ref(&*delegate)));
        // Apple's delegate property is weak. Retain one delegate for the native
        // process lifetime; it owns no per-event objects or retain cycles.
        std::mem::forget(delegate);
        let app = app.clone();
        std::thread::spawn(move || poll_queue(app, shell));
    }

    pub(super) fn permission(request: bool) -> Result<String, String> {
        let center = UNUserNotificationCenter::currentNotificationCenter();
        if request {
            let (sender, receiver) = mpsc::channel();
            let block = RcBlock::new(move |granted: Bool, error: *mut NSError| {
                let result = if error.is_null() {
                    Ok(granted.as_bool())
                } else {
                    // SAFETY: Apple owns a live NSError during this callback.
                    Err(unsafe { &*error }.localizedDescription().to_string())
                };
                let _ = sender.send(result);
            });
            center.requestAuthorizationWithOptions_completionHandler(
                UNAuthorizationOptions::Alert
                    | UNAuthorizationOptions::Sound
                    | UNAuthorizationOptions::Badge,
                &block,
            );
            receiver.recv_timeout(Duration::from_secs(90)).map_err(|_| "Notification permission request timed out. Check System Settings and try again.".to_string())??;
        }
        let (sender, receiver) = mpsc::channel();
        let block = RcBlock::new(move |settings: NonNull<UNNotificationSettings>| {
            // SAFETY: Apple owns a non-null settings object during the callback.
            let status = unsafe { settings.as_ref() }.authorizationStatus();
            let value = match status {
                UNAuthorizationStatus::Authorized
                | UNAuthorizationStatus::Provisional
                | UNAuthorizationStatus::Ephemeral => "granted",
                UNAuthorizationStatus::Denied => "denied",
                UNAuthorizationStatus::NotDetermined => "not-determined",
                _ => "unknown",
            };
            let _ = sender.send(value.to_owned());
        });
        center.getNotificationSettingsWithCompletionHandler(&block);
        receiver
            .recv_timeout(Duration::from_secs(5))
            .map_err(|_| "Could not read macOS notification permission.".into())
    }

    pub(super) fn submit(id: &str, title: &str, body: &str, route: &str) -> Result<(), String> {
        let route = notification_route(route).ok_or("Invalid notification destination.")?;
        let identifier = format!("autohand-squad:{id}");
        let routes = CLICK_ROUTES.get_or_init(Default::default);
        lock(routes).insert(identifier.clone(), route);
        let content = UNMutableNotificationContent::new();
        content.setTitle(&NSString::from_str(title));
        content.setBody(&NSString::from_str(body));
        content.setSound(Some(&UNNotificationSound::defaultSound()));
        let request = UNNotificationRequest::requestWithIdentifier_content_trigger(
            &NSString::from_str(&identifier),
            &content,
            None,
        );
        let (sender, receiver) = mpsc::channel();
        let block = RcBlock::new(move |error: *mut NSError| {
            let result = if error.is_null() {
                Ok(())
            } else {
                // SAFETY: Apple owns a live NSError during this callback.
                Err(unsafe { &*error }.localizedDescription().to_string())
            };
            let _ = sender.send(result);
        });
        UNUserNotificationCenter::currentNotificationCenter()
            .addNotificationRequest_withCompletionHandler(&request, Some(&block));
        let result = receiver
            .recv_timeout(Duration::from_secs(5))
            .map_err(|_| "macOS did not confirm notification submission.".to_string())?;
        if result.is_err() {
            lock(routes).remove(&identifier);
        }
        result
    }

    fn poll_queue(app: AppHandle, shell: Arc<Shell>) {
        let Ok(client) = reqwest::blocking::Client::builder()
            .timeout(Duration::from_secs(4))
            .build()
        else {
            return;
        };
        let mut submitted: HashSet<String> = HashSet::new();
        loop {
            std::thread::sleep(Duration::from_secs(2));
            let Some(bridge) = lock(&shell.app_url).clone() else {
                continue;
            };
            let Ok(response) = client
                .get(format!(
                    "{}/api/notifications",
                    bridge.trim_end_matches('/')
                ))
                .send()
            else {
                continue;
            };
            let mut bytes = Vec::new();
            if response
                .take(2 * 1024 * 1024)
                .read_to_end(&mut bytes)
                .is_err()
            {
                continue;
            }
            let Ok(payload) = serde_json::from_slice::<serde_json::Value>(&bytes) else {
                continue;
            };
            let Some(items) = payload
                .get("data")
                .and_then(|data| data.get("items"))
                .and_then(|items| items.as_array())
            else {
                continue;
            };
            let feed_ids: HashSet<&str> = items
                .iter()
                .take(100)
                .filter_map(|item| item.get("id").and_then(|value| value.as_str()))
                .collect();
            submitted.retain(|id| feed_ids.contains(id.as_str()));
            lock(CLICK_ROUTES.get_or_init(Default::default)).retain(|identifier, _| {
                identifier == "autohand-squad:squad-test"
                    || identifier
                        .strip_prefix("autohand-squad:")
                        .is_some_and(|id| feed_ids.contains(id))
            });
            // Restore click targets from acknowledged events on relaunch. The
            // OS can keep delivered notifications across process lifetimes.
            for item in items.iter().take(100) {
                if let (Some(id), Some(route)) = (
                    item.get("id").and_then(|value| value.as_str()),
                    item.get("route")
                        .and_then(|value| value.as_str())
                        .and_then(notification_route),
                ) {
                    lock(CLICK_ROUTES.get_or_init(Default::default))
                        .insert(format!("autohand-squad:{id}"), route);
                }
            }
            if permission(false).as_deref() != Ok("granted") {
                continue;
            }
            for item in items.iter().rev().take(100) {
                let Some(id) = item.get("id").and_then(|value| value.as_str()) else {
                    continue;
                };
                if submitted.contains(id)
                    || item.get("suppressed").and_then(|value| value.as_bool()) == Some(true)
                    || item
                        .pointer("/native/method")
                        .and_then(|value| value.as_str())
                        != Some("desktop-pending")
                {
                    continue;
                }
                let (Some(title), Some(body), Some(route)) = (
                    item.get("title").and_then(|value| value.as_str()),
                    item.get("body").and_then(|value| value.as_str()),
                    item.get("route").and_then(|value| value.as_str()),
                ) else {
                    continue;
                };
                let result = submit(id, title, body, route);
                if result.is_ok() {
                    submitted.insert(id.to_owned());
                }
                let acknowledgement =
                    serde_json::json!({"id":id,"posted":result.is_ok(),"error":result.err()});
                let _ = client
                    .post(format!(
                        "{}/api/notifications/native-delivery",
                        bridge.trim_end_matches('/')
                    ))
                    .json(&acknowledgement)
                    .send();
            }
            // Keep the worker alive while all windows are hidden in the tray.
            let _ = &app;
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn notification_clicks_accept_only_local_product_routes() {
        for route in [
            "/work?task=abc",
            "/squad",
            "/channels/general",
            "/conversations/new?member=noah",
            "/conversations/abc",
        ] {
            assert!(notification_route(route).is_some(), "{route}");
        }
        for route in [
            "https://example.com",
            "//example.com",
            "/run-shell",
            "/conversations/new?member=../x",
            "/work#script",
            "/channels/../evil",
        ] {
            assert!(notification_route(route).is_none(), "{route}");
        }
    }
}
