import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { readAppInfo, readSourceIdentity } from '../server/app-info.mjs';
import { stageAppInfo } from './stage-app-info.mjs';

const rootDir = await mkdtemp(join(tmpdir(), 'squad-app-info-'));
const runtimeDir = join(rootDir, 'src-tauri', 'runtime');
const originalExecutable = process.execPath;
function git(args) {
  const result = spawnSync('git', ['-C', rootDir, ...args], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  return result.stdout.trim();
}
try {
  await mkdir(join(rootDir, 'public', 'fonts'), { recursive: true });
  await writeFile(join(rootDir, 'package.json'), JSON.stringify({ version: '1.2.3', dependencies: { alpha: '1.0.0' }, autohand: { cliVersion: '0.9.7' } }));
  for (const [name, value] of [['CHANGELOG.md', '# Changes\nA meaningful change.'], ['LICENSE', 'MIT License\nSquad fixture notice.'], ['SECURITY.md', '# Report privately']]) await writeFile(join(rootDir, name), value);
  await writeFile(join(rootDir, 'public', 'fonts', 'ATTRIBUTION.md'), 'Font fixture attribution.');
  await writeFile(join(rootDir, 'public', 'fonts', 'OFL-AutohandMono.txt'), 'Mono OFL fixture notice.');
  await mkdir(join(rootDir, 'daemon'));
  await writeFile(join(rootDir, 'daemon', 'Cargo.lock'), 'version = 4\n\n[[package]]\nname = "squad-notice-fixture-uncached"\nversion = "99.0.0"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n');
  git(['init']);
  git(['config', 'user.name', 'Fixture']);
  git(['config', 'user.email', 'fixture@example.test']);
  git(['add', '.']);
  git(['commit', '-m', 'Fixture identity']);
  const committed = git(['rev-parse', 'HEAD']);
  await mkdir(join(runtimeDir, 'dist'), { recursive: true });
  await writeFile(join(runtimeDir, 'dist', 'index.html'), '<main>first</main>');
  await mkdir(join(rootDir, 'node_modules', 'alpha'), { recursive: true });
  await writeFile(join(rootDir, 'node_modules', 'alpha', 'package.json'), JSON.stringify({ name: 'alpha', version: '1.0.0', license: 'MIT', dependencies: { beta: '2.0.0' } }));
  await writeFile(join(rootDir, 'node_modules', 'alpha', 'LICENSE'), 'Alpha actual notice.');
  await mkdir(join(rootDir, 'node_modules', 'beta'), { recursive: true });
  await writeFile(join(rootDir, 'node_modules', 'beta', 'package.json'), JSON.stringify({ name: 'beta', version: '2.0.0', license: 'Apache-2.0' }));
  assert.deepEqual(readSourceIdentity(rootDir), { commitHash: committed, dirty: false }, 'generated frontend/modules are not uncommitted source');
  const first = await stageAppInfo({ rootDir, runtimeDir, nodeVersion: 'v0.0.0-fixture' });
  assert.equal(first.version, '1.2.3');
  assert.equal(first.commitHash, committed);
  assert.equal(first.dirty, false);
  assert.equal(first.thirdPartyLicenses.find((item) => item.name === 'alpha').text.includes('Alpha actual notice.'), true);
  const beta = first.thirdPartyLicenses.find((item) => item.name === 'beta');
  assert.equal(beta.license, 'Apache-2.0');
  assert.equal(beta.text, '');
  assert.match(beta.note, /No license or notice text/);
  const crate = first.thirdPartyLicenses.find((item) => item.name === 'squad-notice-fixture-uncached');
  assert.equal(crate.version, '99.0.0');
  assert.equal(crate.text, '');
  assert.match(crate.note, /not cached/);
  assert.equal(first.thirdPartyLicenses.find((item) => item.name === 'Node.js').text, '');
  assert.match(first.thirdPartyLicenses.find((item) => item.name === 'Node.js').note, /exact staged Node version/);
  assert.match(first.thirdPartyLicenses.find((item) => item.name === 'Autohand Code CLI').note, /pinned CLI license text/);
  for (const name of ['CHANGELOG.md', 'LICENSE', 'SECURITY.md']) assert.equal(await readFile(join(runtimeDir, name), 'utf8'), await readFile(join(rootDir, name), 'utf8'));
  await writeFile(join(runtimeDir, 'dist', 'index.html'), '<main>different bytes</main>');
  await writeFile(join(rootDir, 'package.json'), JSON.stringify({ version: '1.2.4', dependencies: { alpha: '1.0.0' }, autohand: { cliVersion: '0.9.7' } }));
  const second = await stageAppInfo({ rootDir, runtimeDir, nodeVersion: 'v0.0.0-fixture' });
  assert.equal(second.version, '1.2.4');
  assert.equal(second.commitHash, committed);
  assert.equal(second.dirty, true);
  assert.notEqual(second.frontendSha256, first.frontendSha256, 'frontend digest follows actual built bytes');

  await mkdir(join(rootDir, 'public', 'legal'));
  await mkdir(join(runtimeDir, 'vendor', 'autohand-cli'), { recursive: true });
  await writeFile(join(runtimeDir, 'vendor', 'autohand-cli', 'BUILD_INFO.json'), JSON.stringify({ version: '0.9.7', repository: 'autohandai/code-cli' }));
  await writeFile(join(rootDir, 'package.json'), JSON.stringify({ version: '1.2.4', dependencies: { alpha: '1.0.0' }, autohand: { cliVersion: '0.9.7', cliRepository: 'autohandai/code-cli' } }));
  await writeFile(join(rootDir, 'public', 'legal', 'autohand-code-cli-v0.9.8.LICENSE'), 'MIT License\nA different release notice.');
  const missingPin = await stageAppInfo({ rootDir, runtimeDir, nodeVersion: 'v0.0.0-fixture' });
  assert.equal(missingPin.thirdPartyLicenses.find((item) => item.ecosystem === 'CLI').text, '', 'another version notice must not identify the bundled CLI');
  await writeFile(join(rootDir, 'public', 'legal', 'autohand-code-cli-v0.9.7.LICENSE'), 'Apache License\nExact pinned release notice.');
  await writeFile(join(runtimeDir, 'vendor', 'autohand-cli', 'LICENSE'), 'MIT License\nUnpinned bundled notice.');
  await writeFile(join(runtimeDir, 'DESKTOP_RUNTIME.json'), JSON.stringify({ node: 'v0.0.0-fixture-metadata' }));
  const pinned = await stageAppInfo({ rootDir, runtimeDir });
  const pinnedCli = pinned.thirdPartyLicenses.find((item) => item.ecosystem === 'CLI');
  assert.equal(pinnedCli.text, 'Apache License\nExact pinned release notice.');
  assert.equal(pinnedCli.license, 'Apache-2.0');
  assert.match(pinnedCli.note, /public\/legal\/autohand-code-cli-v0\.9\.7\.LICENSE/);
  assert.match(pinnedCli.note, /autohandai\/code-cli/);
  assert.equal(pinned.nodeVersion, 'v0.0.0-fixture-metadata', 'selected sidecar metadata takes precedence over the generator Node version');
  await rm(join(runtimeDir, 'vendor', 'autohand-cli', 'LICENSE'));
  await writeFile(join(rootDir, 'package.json'), JSON.stringify({ version: '1.2.4', dependencies: { alpha: '1.0.0' }, autohand: { cliVersion: '0.9.7', cliRepository: 'different/repository' } }));
  const wrongRepository = await stageAppInfo({ rootDir, runtimeDir, nodeVersion: 'v0.0.0-fixture' });
  assert.equal(wrongRepository.thirdPartyLicenses.find((item) => item.ecosystem === 'CLI').text, '', 'checked-in pin is only used when BUILD_INFO and package repositories agree');

  const fakeBin = join(rootDir, 'installed-bin');
  await mkdir(fakeBin);
  process.execPath = join(fakeBin, process.platform === 'win32' ? 'node.exe' : 'node');
  const development = await readAppInfo({ rootDir });
  assert.equal(development.metadataSource, 'source');
  assert.equal(development.appExecutableSha256, null);
  assert.equal(development.builtAt, null);
  const nativeExecutable = join(fakeBin, process.platform === 'win32' ? 'autohand-squad.exe' : 'autohand-squad');
  await writeFile(nativeExecutable, 'actual desktop bytes');
  const bundled = await readAppInfo({ rootDir: runtimeDir });
  assert.equal(bundled.metadataSource, 'bundled');
  assert.equal(bundled.appExecutableLabel, 'Desktop executable SHA-256');
  assert.match(bundled.appExecutableSha256, /^[a-f0-9]{64}$/);
  await writeFile(nativeExecutable, 'changed desktop executable bytes');
  const changed = await readAppInfo({ rootDir: runtimeDir });
  assert.notEqual(changed.appExecutableSha256, bundled.appExecutableSha256, 'checksum hashes running app file, not source revision or Node');
  console.log('App information checks passed: source/version/dirty evidence, frontend bytes, notice completeness, shipped documents and native executable checksum.');
} finally {
  process.execPath = originalExecutable;
  await rm(rootDir, { recursive: true, force: true });
}
