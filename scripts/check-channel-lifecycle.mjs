import assert from 'node:assert/strict';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { startBridge, startBrowser, until } from './lib/reliability-browser.mjs';

const bridge = await startBridge();
const failures = [];
const check = async (label, fn) => {
  try { await fn(); console.log(`ok ${label}`); }
  catch (error) { failures.push({ label, error: error.message }); console.error(`FAIL ${label}: ${error.message}`); }
};
let browser;
try {
  await check('channel project configuration survives the real backend', async () => {
    const created = await bridge.api('/api/channels', 'POST', { id: 'project-channel', name: 'project-work', projects: [{ name: 'squad', path: process.cwd() }], section: 'Engineering', memberIds: ['iris', 'iris', 'eva'] });
    assert.equal(created.status, 201);
    assert.equal(created.data.projects?.[0]?.path, process.cwd());
    assert.equal(created.data.section, 'Engineering');
    const saved = (await bridge.api('/api/channels')).data.channels.find(channel => channel.id === created.data.id);
    assert.deepEqual(saved.memberIds, ['iris', 'eva']);
    assert.deepEqual(saved.projects, created.data.projects);
  });
  await check('concurrent creation retains every channel', async () => {
    const results = await Promise.all(Array.from({ length: 12 }, (_, i) => bridge.api('/api/channels', 'POST', { id: `concurrent-${i}`, name: `concurrent-${i}` })));
    assert.ok(results.every(result => result.status === 201));
    const state = (await bridge.api('/api/channels')).data;
    assert.equal(state.channels.filter(channel => channel.id.startsWith('concurrent-')).length, 12);
  });
  await check('duplicate submissions reuse the channel and names cannot collide', async () => {
    const body = { id: 'retry-channel', name: 'retry-work' };
    const first = await bridge.api('/api/channels', 'POST', body);
    const retry = await bridge.api('/api/channels', 'POST', body);
    assert.equal(retry.success, true);
    assert.equal(retry.data.id, first.data.id);
    const duplicate = await bridge.api('/api/channels', 'POST', { name: ' RETRY-WORK ' });
    assert.equal(duplicate.status, 409);
  });
  await check('editing, concurrent membership, messages and threads survive bridge restart', async () => {
    const updated = await bridge.api('/api/channels/project-channel', 'PATCH', { name: 'project-renamed', visibility: 'private', section: 'Projects', autoModeDefault: true, projects: [{ name: 'source', path: process.cwd() }] });
    assert.equal(updated.success, true);
    await Promise.all(Array.from({ length: 8 }, (_, i) => bridge.api('/api/channels/project-channel/members', 'POST', { add: [`member-${i}`] })));
    await bridge.api('/api/channels/project-channel/members', 'POST', { add: ['iris', 'eva'], remove: ['eva'] });
    const now = new Date().toISOString();
    const records = { threads: [{ id: 'thread-persistent', channelId: 'project-channel', title: 'Persistent work', memberIds: ['iris'], createdAt: now, updatedAt: now }], messages: [{ id: 'message-persistent', channelId: 'project-channel', threadId: 'thread-persistent', role: 'user', body: 'Retain this conversation', createdAt: now, updatedAt: now }] };
    assert.equal((await bridge.api('/api/channels/sync', 'PUT', records)).success, true);
    await bridge.restart();
    const state = (await bridge.api('/api/channels')).data;
    const saved = state.channels.find(channel => channel.id === 'project-channel');
    assert.equal(saved.name, 'project-renamed'); assert.equal(saved.visibility, 'private');
    assert.equal(saved.section, 'Projects'); assert.equal(saved.autoModeDefault, true);
    assert.equal(saved.projects[0].path, process.cwd());
    assert.equal(saved.memberIds.length, 9); assert.ok(!saved.memberIds.includes('eva'));
    assert.equal(state.messages.find(message => message.id === 'message-persistent').body, 'Retain this conversation');
    assert.equal((await bridge.api('/api/channels/project-channel/threads')).data[0].id, 'thread-persistent');
  });
  await check('stale snapshots conflict and additive sync cannot lose channels or revive deletion', async () => {
    const stale = (await bridge.api('/api/channels')).data;
    await bridge.api('/api/channels', 'POST', { id: 'after-snapshot', name: 'after-snapshot' });
    const conflict = await bridge.api('/api/channels', 'PUT', stale);
    assert.equal(conflict.status, 409);
    await bridge.api('/api/channels/sync', 'PUT', stale);
    assert.ok((await bridge.api('/api/channels')).data.channels.some(channel => channel.id === 'after-snapshot'));
    assert.equal((await bridge.api('/api/channels/project-channel', 'DELETE')).success, true);
    await bridge.api('/api/channels/sync', 'PUT', stale);
    await bridge.restart();
    const state = (await bridge.api('/api/channels')).data;
    assert.ok(!state.channels.some(channel => channel.id === 'project-channel'));
    assert.ok(!state.messages.some(message => message.channelId === 'project-channel'));
    assert.ok(!state.threads.some(thread => thread.channelId === 'project-channel'));
    assert.equal((await bridge.api('/api/channels/project-channel/members', 'POST', { add: ['iris'] })).status, 404);
    assert.equal((await bridge.api('/api/channels', 'POST', { name: '' })).status, 400);
  });
  await check('channel history larger than one MiB syncs and survives restart', async () => {
    const created = await bridge.api('/api/channels', 'POST', { id: 'large-history', name: 'large-history' });
    assert.equal(created.success, true);
    const messages = Array.from({ length: 160 }, (_, i) => ({ id: `large-message-${i}`, channelId: created.data.id, body: 'history '.repeat(1024), role: 'user' }));
    const payload = { channels: [created.data], messages };
    assert.ok(Buffer.byteLength(JSON.stringify(payload)) > 1024 * 1024);
    const synced = await bridge.api('/api/channels/sync', 'PUT', payload);
    assert.equal(synced.status, 200, synced.error);
    await bridge.restart();
    const saved = (await bridge.api('/api/channels')).data;
    assert.equal(saved.messages.filter(item => item.channelId === created.data.id).length, messages.length);
    assert.equal(saved.messages.find(item => item.id === messages.at(-1).id).body, messages.at(-1).body);
    const replaced = await bridge.api('/api/channels', 'PUT', saved);
    assert.equal(replaced.status, 200, replaced.error);
    const path = join(bridge.directory, 'squad', 'channels.json');
    const before = await readFile(path, 'utf8');
    const oversized = await bridge.api('/api/channels/sync', 'PUT', { messages: [{ id: 'too-large', channelId: created.data.id, body: 'x'.repeat(16 * 1024 * 1024) }] });
    assert.equal(oversized.status, 413);
    assert.equal(await readFile(path, 'utf8'), before, 'Rejected input must leave saved history intact');
    assert.equal((await bridge.api('/api/channels', 'POST', { name: 'too-large', purpose: 'x'.repeat(1024 * 1024) })).status, 413, 'Individual mutations keep the original limit');
  });
  await check('legacy documents migrate and damaged persistence cannot be overwritten', async () => {
    const path = join(bridge.directory, 'squad', 'channels.json');
    const saved = await readFile(path, 'utf8');
    await writeFile(path, JSON.stringify([{ id: 'legacy', name: 'legacy', memberIds: ['iris'] }]));
    await bridge.restart();
    assert.equal((await bridge.api('/api/channels')).data.channels[0].name, 'legacy');
    assert.equal((await bridge.api('/api/channels/legacy', 'PATCH', { autoModeDefault: true })).success, true);
    await writeFile(path, '{damaged');
    const failed = await bridge.api('/api/channels', 'POST', { name: 'must-not-overwrite' });
    assert.equal(failed.success, false);
    assert.match(failed.error, /Saved channel history is damaged.*backup/);
    assert.equal(await readFile(path, 'utf8'), '{damaged');
    await writeFile(path, saved);
  });
  await check('a torn-tail document recovers with its original kept and agent channel routes stay loaded', async () => {
    const path = join(bridge.directory, 'squad', 'channels.json');
    const saved = await readFile(path, 'utf8');
    const expected = JSON.parse(saved);
    // 0.1.5 wrote channels.json from two unserialised writers; a shorter
    // document overwriting a longer one left the old closing brace behind.
    const torn = `${saved.trimEnd()}\n}\n`;
    await writeFile(path, torn);
    await bridge.restart();
    const state = await bridge.api('/api/channels');
    assert.equal(state.status, 200, state.error);
    assert.equal(state.data.channels.length, expected.channels.length);
    assert.equal(state.data.messages.length, expected.messages.length);
    assert.equal(JSON.parse(await readFile(path, 'utf8')).channels.length, expected.channels.length, 'the saved file is valid JSON again');
    const backups = (await readdir(join(bridge.directory, 'squad'))).filter(name => name.startsWith('channels.json.damaged-'));
    assert.equal(backups.length, 1, 'the damaged original is kept beside the recovered file');
    assert.equal(await readFile(join(bridge.directory, 'squad', backups[0]), 'utf8'), torn);
    assert.equal((await bridge.api('/api/channel-actions')).status, 200, 'agent channel routes load after recovery');
    assert.equal((await bridge.api('/api/channels', 'POST', { name: 'after-recovery' })).status, 201);
    await writeFile(path, `${saved.trimEnd()}\n{"not": "a closer"}\n`);
    await bridge.restart();
    assert.equal((await bridge.api('/api/channels')).status, 409, 'arbitrary trailing content is not recovered');
    await writeFile(path, '{damaged');
    await bridge.restart();
    const actions = await bridge.api('/api/channel-actions');
    assert.equal(actions.status, 409, 'damaged history must not unload the agent channel routes');
    assert.match(actions.error, /Saved channel history is damaged/);
    assert.equal((await bridge.api('/api/channels')).status, 409);
    assert.equal(await readFile(path, 'utf8'), '{damaged');
    await writeFile(path, saved);
    await bridge.restart();
  });
  if (!process.argv.includes('--api-only')) await check('normal sidebar can create a channel, reopen the dialog and show failed saves', async () => {
    browser = await startBrowser();
    await browser.send('Page.addScriptToEvaluateOnNewDocument', { source: `if (!localStorage.getItem('reliability.seeded')) { localStorage.setItem('autohandSquad.v1.onboarding', JSON.stringify({version:1,status:'skipped'})); localStorage.setItem('reliability.seeded','true'); }` });
    await browser.navigate(bridge.origin + '/squad');
    await until(() => browser.evaluate(`!!document.querySelector('button[aria-label="Create channel"]')`), 'sidebar channel creation');
    await browser.click('Create channel');
    await until(() => browser.evaluate(`!!document.querySelector('#channel-name')`), 'first create dialog');
    await browser.fill('#channel-name', 'browser-lifecycle');
    await browser.evaluate(`document.querySelector('#channel-name').form.requestSubmit()`);
    await until(() => browser.evaluate(`location.pathname.startsWith('/channels/') && !document.querySelector('#channel-name')`), 'created channel navigation');
    await until(async () => (await bridge.api('/api/channels')).data.channels.some(channel => channel.name === 'browser-lifecycle'), 'real persisted browser channel');
    await browser.click('Create channel');
    await until(() => browser.evaluate(`!!document.querySelector('#channel-name')`), 'reopened create dialog', 2500);
    await browser.fill('#channel-name', 'browser-lifecycle');
    await browser.evaluate(`document.querySelector('#channel-name').form.requestSubmit()`);
    await until(() => browser.evaluate(`!!document.querySelector('[role="alert"]') && !!document.querySelector('#channel-name')`), 'duplicate error with preserved draft');
    await browser.fill('#channel-name', 'browser-second');
    await browser.evaluate(`document.querySelector('#channel-name').form.requestSubmit()`);
    await until(() => browser.evaluate(`!document.querySelector('#channel-name') && document.querySelector('main h1')?.textContent.includes('browser-second')`), 'second created channel');
    await browser.evaluate(`document.querySelector('main header button[aria-label="Settings"]').click()`);
    await until(() => browser.evaluate(`!!document.querySelector('#channel-details-name')`), 'channel details');
    await browser.fill('#channel-details-name', 'browser-renamed');
    await browser.fill('#channel-details-section', 'Engineering');
    await browser.evaluate(`document.querySelector('#channel-details-visibility').click()`);
    await until(() => browser.evaluate(`!![...document.querySelectorAll('[role="option"]')].find(option => option.textContent === 'Private')`), 'visibility options');
    await browser.evaluate(`[...document.querySelectorAll('[role="option"]')].find(option => option.textContent === 'Private').click()`);
    await browser.click('Save channel');
    await until(() => browser.evaluate(`document.querySelector('main h1')?.textContent.includes('browser-renamed')`), 'confirmed UI rename');
    const channel = (await bridge.api('/api/channels')).data.channels.find(item => item.name === 'browser-renamed');
    assert.equal(channel.section, 'Engineering');
    assert.equal(channel.visibility, 'private');
    await browser.evaluate(`[...document.querySelectorAll('button[role="combobox"]')].find(button => button.textContent.includes('Add a known folder')).click()`);
    await until(() => browser.evaluate(`!!document.querySelector('[role="option"]')`), 'known project folders');
    await browser.evaluate(`document.querySelector('[role="option"]').click()`);
    const configured = await until(async () => (await bridge.api('/api/channels')).data.channels.find(item => item.id === channel.id)?.projects?.length === 1 && (await bridge.api('/api/channels')).data.channels.find(item => item.id === channel.id), 'confirmed project from normal UI');
    const project = configured.projects[0];
    assert.ok((await bridge.api('/api/workspaces')).data.some(workspace => workspace.path === project.path) || (await bridge.api('/api/runtime')).data.defaultWorkspace === project.path, 'UI project must be a real offered folder');
    await browser.click('Remove ' + project.name);
    await until(async () => !(await bridge.api('/api/channels')).data.channels.find(item => item.id === channel.id).projects.length, 'confirmed project removal');
    await browser.evaluate(`[...document.querySelectorAll('button[role="combobox"]')].find(button => button.textContent.includes('Add a known folder')).click()`);
    await until(() => browser.evaluate(`!!document.querySelector('[role="option"]')`), 'project restoration options');
    await browser.evaluate(`document.querySelector('[role="option"]').click()`);
    await until(async () => (await bridge.api('/api/channels')).data.channels.find(item => item.id === channel.id).projects.some(item => item.path === project.path), 'confirmed project restoration');
    await browser.evaluate(`document.querySelector('main h1').click()`);
    await browser.click('Manage members');
    await until(() => browser.evaluate(`!!document.querySelector('main button[role="checkbox"]')`), 'membership controls');
    const selectedMember = await browser.evaluate(`(() => { const members = JSON.parse(localStorage.getItem('autohandSquad.v1.agents')); const button = document.querySelector('main button[role="checkbox"]'); return members.find(member => button.textContent.includes(member.name)); })()`);
    assert.ok(selectedMember);
    const toggleMember = () => browser.evaluate(`[...document.querySelectorAll('main button[role="checkbox"]')].find(button => button.textContent.includes(${JSON.stringify(selectedMember.name)})).click()`);
    await toggleMember();
    await until(async () => (await bridge.api('/api/channels')).data.channels.find(item => item.id === channel.id).memberIds.includes(selectedMember.id), 'confirmed member addition');
    await until(() => browser.evaluate(`[...document.querySelectorAll('main button[role="checkbox"]')].find(button => button.textContent.includes(${JSON.stringify(selectedMember.name)}))?.getAttribute('aria-checked') === 'true'`), 'rendered member addition');
    await toggleMember();
    await until(async () => !(await bridge.api('/api/channels')).data.channels.find(item => item.id === channel.id).memberIds.includes(selectedMember.id), 'confirmed member removal');
    await until(() => browser.evaluate(`[...document.querySelectorAll('main button[role="checkbox"]')].find(button => button.textContent.includes(${JSON.stringify(selectedMember.name)}))?.getAttribute('aria-checked') === 'false'`), 'rendered member removal');
    await toggleMember();
    await until(async () => (await bridge.api('/api/channels')).data.channels.find(item => item.id === channel.id).memberIds.includes(selectedMember.id), 'confirmed member restoration');
    await bridge.restart();
    await browser.navigate(bridge.origin + '/channels/' + channel.id);
    await until(() => browser.evaluate(`document.querySelector('main h1')?.textContent.includes('browser-renamed')`), 'reopen persisted channel after restart');
    const reopened = (await bridge.api('/api/channels')).data.channels.find(item => item.id === channel.id);
    assert.equal(reopened.visibility, 'private');
    assert.ok(reopened.projects.some(item => item.path === project.path));
    assert.ok(reopened.memberIds.includes(selectedMember.id));
    await browser.screenshot('.codex-artifacts/reliability/channels.png');
    await browser.evaluate(`document.querySelector('main header button[aria-label="Settings"]').click()`);
    await until(() => browser.evaluate(`!!document.querySelector('#channel-details-name')`), 'reopened deletion settings');
    await browser.click('Delete channel'); await browser.click('Delete channel?');
    await until(async () => !(await bridge.api('/api/channels')).data.channels.some(item => item.id === channel.id), 'confirmed normal UI deletion');
    assert.deepEqual(browser.errors, []);
  });
} finally { await browser?.close(); await bridge.close(); }
if (failures.length) { console.error(JSON.stringify(failures, null, 2)); process.exitCode = 1; }
else console.log('Channel lifecycle checks passed (real local backend; no provider execution).');
