import assert from 'node:assert/strict';
import { channelTranscript } from '../src/lib/channel-transcript.js';

const thread = { id: 'saved', channelId: 'channel', title: 'Saved work', replyCount: 2, createdAt: '2026-10-13T00:00:00Z' };
const archived = channelTranscript([], [thread], 'channel');
assert.equal(archived.length, 1);
assert.equal(archived[0].role, 'system');
assert.equal(archived[0].authorName, 'Squad');
assert.equal(archived[0].status, 'record');
assert.equal(archived[0].threadId, thread.id);
assert.match(archived[0].body, /Saved work\n\n2 replies were recorded in this thread/);
assert.match(archived[0].body, /unavailable on this device/);
assert.deepEqual(channelTranscript(archived, [thread], 'channel'), archived, 'projection is idempotent');
const root = { id: 'saved-root', threadId: 'saved', role: 'user', body: 'Actual prompt' };
const reply = { id: 'reply', parentMessageId: 'saved-root', threadId: 'saved', role: 'agent', body: 'Actual reply' };
const original = [root, reply];
assert.deepEqual(channelTranscript(original, [thread], 'channel'), original, 'complete transcript stays unchanged');
assert.equal(channelTranscript(original, [thread], 'channel')[0], root);
const partial = channelTranscript([reply], [thread], 'channel');
assert.equal(partial[0], reply);
assert.match(partial[1].body, /1 is unavailable/);
assert.equal(partial.filter(message => message.role === 'agent').length, 1, 'never invent replies');
const foreign = channelTranscript([], [{ ...thread, channelId: 'other' }], 'channel');
assert.deepEqual(foreign, [], 'do not display other channels');
assert.deepEqual(channelTranscript([], [thread, thread], 'channel'), archived, 'deduplicate thread metadata');
assert.deepEqual(channelTranscript(null, null), []);
assert.equal(thread.replyCount, 2);
assert.deepEqual(original, [root, reply]);
assert.match(channelTranscript([], [{ ...thread, replyCount: -2 }], 'channel')[0].body, /Only the thread record/);
assert.match(channelTranscript([], [{ ...thread, replyCount: Infinity }], 'channel')[0].body, /Only the thread record/);
assert.match(channelTranscript([reply], [{ ...thread, replyCount: 1 }], 'channel')[1].body, /original prompt is unavailable/);
console.log('Channel transcript checks passed: archived/partial roots, unchanged records, missing content disclosure, deduplication and channel isolation.');
