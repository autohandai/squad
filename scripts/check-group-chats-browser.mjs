import assert from 'node:assert/strict';
import { startBridge, startBrowser, until } from './lib/reliability-browser.mjs';
import { seedOwnedBrowserFixture } from './lib/owned-bridge-fixture.mjs';
import { prepareModelRoutingFixture } from './lib/model-routing-fixtures.mjs';

const bridge = await startBridge({ development: false, prepare: prepareModelRoutingFixture });
let browser;
try {
  browser = await startBrowser();
  await browser.send('Page.addScriptToEvaluateOnNewDocument', { source: `
    const originalFetch = window.fetch.bind(window);
    window.fetch = async (input, init) => {
      const response = await originalFetch(input, init);
      const url = new URL(typeof input === 'string' ? input : input.url, location.origin);
      if (init?.method === 'PATCH' && /^\\/api\\/channels\\/[^/]+$/.test(url.pathname) && response.ok) {
        await new Promise(resolve => setTimeout(resolve, 300));
      }
      return response;
    };
  ` });
  const members = ['Eva', 'Noah'].map(name => ({ id: 'group-' + name.toLowerCase(), name, role: 'Reviewer', status: 'online', workspace: process.cwd(), projects: [{ path: process.cwd() }], harness: { id: 'codex' }, permissions: {} }));
  await seedOwnedBrowserFixture(bridge, browser, { members });
  await browser.navigate(bridge.origin + '/squad');
  await until(() => browser.evaluate("document.body.textContent.includes('Eva') && document.body.textContent.includes('Noah')"), 'owned member directory', 30000);
  await browser.evaluate("document.querySelector('button[aria-label=\"New message\"],button[aria-label=\"Add a member or team\"]').click()");
  await until(() => browser.evaluate("!!document.querySelector('[data-testid=conversation-composer]')"), 'DM plus opens the inline recipient composer');
  assert.equal(await browser.evaluate("!!document.querySelector('[role=dialog]')"), false);
  assert.equal(Object.keys((await bridge.api('/api/channels')).data.agentChannelAccess).length, 2, 'opening the composer does not create a placeholder member');
  await browser.click('Select Eva');
  await browser.click('Select Noah');
  await browser.fill('#message-group-name', 'Release reviewers');
  await browser.screenshot('.codex-artifacts/group-chats/recipients-desktop.png');
  await browser.click('Create group chat');
  await until(() => browser.evaluate("location.pathname.startsWith('/channels/group-')"), 'created group conversation');
  const id = await browser.evaluate("decodeURIComponent(location.pathname.split('/').pop())");
  const group = (await bridge.api(`/api/group-chats/${id}`)).data;
  assert.equal(group.kind, 'group');
  assert.equal(group.visibility, 'private');
  assert.deepEqual(group.memberIds, members.map(member => member.id));
  assert.equal(await browser.evaluate("!!document.querySelector('button[aria-label=\"Group chat: Release reviewers\"]')"), true, 'group is a direct-message row');
  await until(() => browser.evaluate("!!document.querySelector('textarea:not(:disabled)')"), 'group message composer');
  await browser.fill('textarea', 'Retain our review.');
  await browser.click('Send');
  await until(async () => {
    const saved = (await bridge.api('/api/channels')).data;
    return saved.messages.filter(message => message.channelId === id && message.role === 'agent' && message.status === 'complete').length === 2;
  }, 'both selected members answer the group message', 60000);
  const beforeConversion = (await bridge.api('/api/channels')).data;
  await browser.navigate(bridge.origin + '/channels/' + id);
  await until(() => browser.evaluate("document.body.textContent.includes('Retain our review.')"), 'saved group history renders');
  await browser.click('Settings');
  await until(() => browser.evaluate("!!document.querySelector('[data-testid=group-conversion]')"), 'explicit group conversion controls');
  await browser.fill('#channel-details-name', 'Release review group');
  await browser.click('Save group');
  await until(async () => (await bridge.api('/api/group-chats/' + id)).data.name === 'Release review group', 'saved group rename');
  await until(() => browser.evaluate("document.getElementById('group-channel-name').value === 'Release review group'"), 'untouched conversion name follows the saved group rename');
  await until(() => browser.evaluate("[...document.querySelectorAll('button')].some(button => button.textContent.trim() === 'Save group')"), 'first group save acknowledgement finishes rendering');
  await browser.fill('#group-channel-name', 'release-reviews');
  await browser.fill('#channel-details-name', 'Launch reviewers');
  await browser.click('Save group');
  await until(async () => (await bridge.api('/api/group-chats/' + id)).data.name === 'Launch reviewers', 'second saved group rename');
  await until(() => browser.evaluate("!!document.querySelector('button[aria-label=\"Group chat: Launch reviewers\"]')"), 'saved group rename renders in its direct-message row');
  await until(() => browser.evaluate("[...document.querySelectorAll('button')].some(button => button.textContent.trim() === 'Save group')"), 'second group save acknowledgement finishes rendering');
  assert.equal(await browser.evaluate("document.getElementById('group-channel-name').value"), 'release-reviews', 'an intentional conversion name is retained across source updates');
  await browser.evaluate("document.getElementById('group-channel-visibility').click()");
  await until(() => browser.evaluate("!!document.querySelector('[role=option]')"), 'channel visibility options');
  await browser.evaluate("[...document.querySelectorAll('[role=option]')].find(option => option.textContent.trim() === 'Public').click()");
  assert.equal(await browser.evaluate("document.querySelector('[data-testid=group-conversion]').textContent.includes('including its existing messages')"), true, 'public conversion explains access to earlier history');
  await browser.click('Convert to public channel');
  await until(async () => (await bridge.api('/api/channels')).data.channels.find(item => item.id === id)?.kind === 'channel', 'group converted to a public channel');
  const afterConversion = (await bridge.api('/api/channels')).data;
  assert.equal(afterConversion.channels.find(item => item.id === id).visibility, 'public');
  assert.deepEqual(afterConversion.messages, beforeConversion.messages, 'app conversion preserves exact messages');
  assert.deepEqual(afterConversion.threads, beforeConversion.threads, 'app conversion preserves exact threads');
  await until(() => browser.evaluate("!document.querySelector('button[aria-label=\"Group chat: Launch reviewers\"]')"), 'converted group leaves direct-message section');
  await browser.navigate(bridge.origin + '/squad');
  await until(() => browser.evaluate("!!document.querySelector('button[aria-label=\"New message\"]')"), 'message action after conversion');
  await browser.click('New message');
  await until(() => browser.evaluate("!!document.querySelector('[data-testid=conversation-composer]')"), 'second recipient composer');
  await browser.fill('input[aria-label="Search recipients"]', 'Noah');
  assert.equal(await browser.evaluate("document.querySelector('[aria-label=Recipients]').innerText.includes('Eva')"), false, 'search narrows the recipient list');
  await browser.click('Select Noah');
  await browser.click('Open chat');
  await until(() => browser.evaluate("new URLSearchParams(location.search).get('member') === 'group-noah'"), 'existing direct conversation selected');
  assert.equal(Object.keys((await bridge.api('/api/channels')).data.agentChannelAccess).length, 2, 'opening an existing direct chat never creates another member');
  await browser.navigate(bridge.origin + '/messages/new');
  await until(() => browser.evaluate("!!document.querySelector('[data-testid=conversation-composer]')"), 'temporary group composer');
  await browser.click('Select Eva'); await browser.click('Select Noah');
  await browser.fill('#message-group-name', 'Temporary group'); await browser.click('Create group chat');
  await until(() => browser.evaluate("location.pathname.startsWith('/channels/group-')"), 'temporary group created');
  const temporaryId = await browser.evaluate("decodeURIComponent(location.pathname.split('/').pop())");
  await browser.click('Settings');
  await until(() => browser.evaluate("!!document.querySelector('[data-testid=group-conversion]')"), 'temporary group settings');
  await browser.click('Delete group chat');
  assert((await bridge.api('/api/channels')).data.channels.some(item => item.id === temporaryId), 'first delete click only asks');
  await browser.click('Delete group chat?');
  await until(async () => (await bridge.api('/api/channels')).data.deletedChannelIds.includes(temporaryId), 'group deleted through the app');
  assert.equal(Object.keys((await bridge.api('/api/channels')).data.agentChannelAccess).length, 2, 'group deletion preserves member profiles');
  await browser.navigate(bridge.origin + '/messages/new');
  await until(() => browser.evaluate("!!document.querySelector('[data-testid=conversation-composer]')"), 'new member composer');
  await browser.click('New member');
  await browser.fill('#message-new-name', 'Tatiana');
  await browser.fill('#message-new-role', 'Software engineer');
  await browser.fill('#message-new-description', 'Owns release compatibility and regression checks.');
  await browser.click('Create member and open chat');
  await until(() => browser.evaluate("new URLSearchParams(location.search).get('member')?.startsWith('member-')"), 'explicitly named member created');
  const memberId = await browser.evaluate("new URLSearchParams(location.search).get('member')");
  const created = (await bridge.api('/api/channels')).data.agentChannelAccess[memberId].agent;
  assert.equal(created.name, 'Tatiana');
  assert.equal(created.role, 'Software engineer');
  assert.equal(created.description, 'Owns release compatibility and regression checks.');
  assert.ok(created.harness.id, 'created member has an automatic primary engine');
  assert.ok(created.modelRouting?.fallbacks.length, 'created member has connected failovers');
  const transcript = (await bridge.api(`/api/members/${memberId}/transcript`)).data;
  assert.equal((transcript.messages || []).length, 0, 'creation does not inject an artificial greeting');
  await browser.navigate(bridge.origin + '/messages/new');
  await until(() => browser.evaluate("!!document.querySelector('[data-testid=conversation-composer]')"), 'responsive recipient composer');
  await browser.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  assert.equal(await browser.evaluate('document.documentElement.scrollWidth <= innerWidth'), true, 'recipient picker fits a phone');
  await browser.screenshot('.codex-artifacts/group-chats/recipients-mobile.png');
  assert.deepEqual(browser.errors, []);
  console.log('PASS: owned rendered DM chooser, search, existing chat, private group create/delete and public conversion retaining exact history, explicit member creation with default/failover, no greeting, desktop and phone.');
} finally { await browser?.close(); await bridge.close(); }
